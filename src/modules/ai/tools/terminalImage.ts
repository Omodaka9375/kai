/**
 * Terminal Image Protocol — iTerm2-style inline image rendering.
 *
 * The OSC 1337 parser here documents the wire format the TERMINAL module
 * (oscImage.ts) renders for PTY-originated sequences (imgcat-style programs).
 *
 * The display_image tool is CHAT-ONLY (2026-11-19): the agent's images go to
 * the chat as media cards. The old second surface — pushing the OSC sequence
 * into the active terminal — misfired twice (the sequence went to shell
 * stdin, typing megabytes of base64 into the live prompt), and even when it
 * worked it dumped content into a terminal the agent had no reason to touch.
 * The user's terminal is the user's; agent output lives in the chat.
 *
 * OSC 1337 format:
 *   ESC ] 1337 ; File=name=<base64name>;size=<bytes>;inline=1:<base64data> BEL
 */

import { tool } from "ai";
import { z } from "zod";
import type { ToolContext } from "./context";
import { nativeForContext } from "./context";
import { resolvePath } from "./context";
import { sniffImageMime } from "../extraction";
import type { NativeClient } from "../lib/native";
import { checkReadableCanonical } from "../lib/security";
import { sandboxOverrideForContext } from "./context";
import { bytesToBase64 } from "../lib/media/bytes";

const MAX_IMAGE_BYTES = 16 * 1024 * 1024;

async function readLocalImage(path: string, client: NativeClient): Promise<string> {
  const bytes = new Uint8Array(await client.readFileBytes(path));
  if (bytes.length === 0 || bytes.length > MAX_IMAGE_BYTES) {
    throw new Error(`image must be 1 byte to 16 MiB; received ${bytes.length} bytes`);
  }
  return bytesToBase64(bytes);
}

/**
 * Parse an OSC 1337 inline image sequence.
 * Returns { name, data } or null if not a valid image sequence.
 */
export function parseOsc1337(oscParams: string): {
  name: string;
  base64Data: string;
} | null {
  // OSC 1337 params look like: File=name=<b64>;size=123;inline=1:<b64data>
  const match = oscParams.match(
    /^File=name=([^;]*);size=\d+;inline=1:(.+)$/,
  );
  if (!match) return null;
  return { name: match[1], base64Data: match[2] };
}



export function buildTerminalImageTools(ctx: ToolContext) {
  return {
    display_image: tool({
      needsApproval: false,
      description:
        "Display an image to the user: an inline image card in the CHAT. " +
        "For a local screenshot or image returned by another tool, pass its path (including absolute Windows paths). For generated bytes, pass base64_data without the data: URL prefix. Exactly one of path or base64_data is required. Use this to show plots, diagrams, screenshots, or AI-generated images without putting the image bytes in the conversation. The image is never written into the user's terminal.",
      inputSchema: z.object({
        path: z
          .string()
          .optional()
          .describe("Path to a local PNG/JPEG/GIF/WEBP file, e.g. a screenshot path returned by Browserr. Preferred over base64_data."),
        base64_data: z
          .string()
          .optional()
          .describe("Base64-encoded image data (PNG/JPEG/GIF/WEBP). Do NOT include the data:image/...;base64, prefix."),
        name: z
          .string()
          .optional()
          .describe("Optional filename for the image."),
      }).refine((input) => Boolean(input.path) !== Boolean(input.base64_data), {
        message: "Provide exactly one of path or base64_data",
      }),
      execute: async ({ path, base64_data, name }) => {
        const imgName = name || path?.split(/[\\/]/).pop() || "image.png";
        if (path) {
          try {
            const abs = resolvePath(path, ctx.getCwd());
            const client = nativeForContext(ctx);
            const safety = await checkReadableCanonical(abs, client.canonicalize, await sandboxOverrideForContext(ctx));
            if (!safety.ok) return { error: safety.reason };
            base64_data = await readLocalImage(safety.canonical, client);
          } catch (e) {
            return { error: `could not read image at "${path}" (${String(e).slice(0, 160)})` };
          }
        }
        if (base64_data === undefined) {
          return { error: "Provide exactly one of path or base64_data" };
        }
        // The name is interpolated straight into an OSC 1337 sequence and written
        // into the live PTY. A name containing `BEL` (`\x07`) or `ESC` (`\x1b`) would
        // terminate the sequence early and inject arbitrary control bytes. Base64
        // alphabet is `[A-Za-z0-9+/=]`; reject anything else so a payload can't
        // smuggle a terminator past the length check.
        if (/[\x00-\x1f\x7f]/.test(imgName)) {
          return { error: "image name must not contain control bytes" };
        }
        if (!/^[A-Za-z0-9+/=]*$/.test(base64_data)) {
          return { error: "base64_data must contain only base64 characters" };
        }
        // CONTENT VALIDATION (2026-11-10 broken-image report): a model that
        // can't easily fetch the real bytes passes a PLACEHOLDER string
        // (literal "PLACEHOLDER" = 12 chars = 9 bytes, seen in a real
        // transcript) and the card renders a broken img. Base64 charset
        // alone can't catch that — validate the decoded payload:
        // (1) must not be a placeholder-ish literal, (2) must be long
        // enough to hold real image bytes (a 1x1 PNG is ~68 bytes), (3) must
        // start with a known image magic (png/jpeg/gif/webp). Reject with a
        // corrective message so the model re-reads the actual file instead
        // of the chat silently showing a broken image.
        if (/^(PLACEHOLDER|TODO|image|base64|data)$/i.test(base64_data.trim())) {
          return {
            error:
              "base64_data looks like a placeholder, not real image bytes. Read the image file and pass its actual base64 content (no placeholder, no truncation).",
          };
        }
        if (base64_data.length < 64) {
          return {
            error: `base64_data is only ${base64_data.length} characters - far too small to be a real image (a 1x1 PNG is ~90 chars). Pass the complete base64 content of the image file.`,
          };
        }
        const magic = sniffImageMime(base64_data);
        const isKnownImage =
          magic === "image/jpeg" ||
          base64_data.startsWith("iVBORw0KGgo") ||
          base64_data.startsWith("R0lGOD") ||
          (base64_data.startsWith("UklGR") && base64_data.length >= 16);
        if (!isKnownImage) {
          return {
            error:
              "base64_data does not start with a recognized image header (PNG/JPEG/GIF/WEBP). Decode it to check: if it is plain text, you passed a description instead of the file's bytes - read the image file and pass its actual base64 content.",
          };
        }
        const sizeBytes = Math.ceil((base64_data.length * 3) / 4);

        // CHAT CARD (2026-11-06, same surface-independence fix as display_
        // video): the base64 is already in hand, so the chat always gets
        // the image — no terminal, no error. MediaMessage's image card
        // accepts { type: "image", base64, mimeType, ... }; dimensions are
        // unknown server-side, the card does not need them to render.
        // Persisted copies elide the input base64 (elideBulkyToolInputs)
        // and the compact stripper drops the output copy on later turns,
        // so this adds no dead context weight.
        const card = {
          type: "image" as const,
          base64: base64_data,
          mimeType: sniffImageMime(base64_data),
          url: "",
          width: 0,
          height: 0,
          provider: "display",
          prompt: imgName,
          ...(path ? { sourcePath: path } : {}),
        };

        // CHAT-ONLY (2026-11-19): the terminal-decoration second surface is
        // GONE — it dumped the OSC 1337 sequence into the user's shell twice
        // (the write path went to PTY stdin, not the xterm parser), and agent
        // output in the user's terminal is wrong even when it renders.
        return {
          ok: true,
          ...card,
          displayed_in: "chat image card",
          size_bytes: sizeBytes,
        };
      },
      toModelOutput: ({ output }): { type: "text"; value: string } => {
        const image = output as {
          sourcePath?: string;
          prompt?: string;
          size_bytes?: number;
          displayed_in?: string;
          error?: string;
        } | undefined;
        return {
          type: "text",
          value: image?.error
            ? `Could not display image: ${image.error}`
            : `Displayed image ${JSON.stringify(image?.prompt ?? "image")} in the user's chat (${image?.size_bytes ?? 0} bytes)${image?.sourcePath ? ` from ${image.sourcePath}` : ""}. The image is for the user, not a command to execute.`,
        };
      },
    }),
  } as const;
}