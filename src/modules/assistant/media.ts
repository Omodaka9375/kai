/**
 * Assistant-native media generation tools.
 *
 * The DESKTOP generate_image/generate_video are async fire-and-forget: their
 * execute() returns {status:"generating"} immediately and the real payload
 * later lands via spawnMediaTask → chatStore.resolveMedia(sessionId, …).
 * Headless (Telegram) there is no chat session to patch — the payload was
 * silently dropped. These tools instead run SYNCHRONOUSLY inside the agent
 * step (blocking is fine: the turn is one-at-a-time) and deliver directly.
 *
 * Provider selection is automatic from configured keys — the user's request
 * "generate an image with google" shouldn't turn into a provider quiz.
 */
import { tool } from "ai";
import { z } from "zod";
import { invoke } from "@tauri-apps/api/core";
import { getKey } from "@/modules/ai/lib/keyring";
import { getTelegramToken, loadAssistantPrefs } from "./index";

type ImageGen = (
  apiKey: string,
  opts: { prompt: string; size?: string; quality?: string; signal?: AbortSignal },
) => Promise<{ base64?: string; url?: string; mimeType: string; width: number; height: number }>;

async function pickImageProvider(): Promise<{ provider: "google" | "openai" | "xai"; key: string } | null> {
  const [google, openai, xai] = await Promise.all([
    getKey("google"),
    getKey("openai"),
    getKey("xai"),
  ]);
  // Prefer google (Nano Banana) — the user's configured default — then openai, then xai.
  if (google) return { provider: "google", key: google };
  if (openai) return { provider: "openai", key: openai };
  if (xai) return { provider: "xai", key: xai };
  return null;
}

async function pickVideoProvider(): Promise<{ provider: "google"; key: string } | null> {
  // Video is Google Veo only — Kling/Seedance are served by their official
  // MCP servers (install in Settings → MCP), not native integrations.
  const google = await getKey("google");
  if (google) return { provider: "google", key: google };
  return null;
}

/** Deliver generated bytes/URL to the owner's Telegram chat. */
async function deliver(
  kind: "image" | "video",
  media: { base64?: string; url?: string; mimeType: string },
  prompt: string,
): Promise<void> {
  const token = await getTelegramToken();
  const prefs = await loadAssistantPrefs();
  const chatId = prefs.ownerChatId;
  if (!token || chatId == null) return;
  const caption = prompt ? prompt.slice(0, 900) : null;
  // URL path (server-side fetch) when the provider gave one and no inline bytes.
  if (!media.base64 && media.url) {
    await invoke("telegram_send_media_url", {
      token,
      chatId,
      url: media.url,
      kind,
      caption,
    }).catch(() => {});
    return;
  }
  const b64 = media.base64;
  if (!b64) return;
  if (kind === "image") {
    const photoOk = /^image\/(png|jpeg|webp)/.test(media.mimeType);
    const send = photoOk ? "telegram_send_photo" : "telegram_send_document";
    await invoke(send, {
      token,
      chatId,
      photoBase64: b64,
      dataBase64: b64,
      caption,
      fileName: "image",
      mimeType: media.mimeType,
    }).catch(() => {});
  } else {
    await invoke("telegram_send_video", {
      token,
      chatId,
      videoBase64: b64,
      caption,
    }).catch(() => {});
  }
}

export function buildAssistantMediaTools(): Record<string, unknown> {
  const generateImage = tool({
    description:
      "Generate an image from a text prompt. The provider is picked automatically from configured keys (google preferred, then openai, then xai). The image is delivered to the user's Telegram chat immediately; describe it briefly in your reply. Size/quality are optional.",
    inputSchema: z.object({
      prompt: z.string().describe("Detailed description of the image: subject, style, composition, lighting."),
      size: z.string().optional().describe("Dimensions like '1024x1024' or '1536x1024'. Default 1024x1024."),
    }),
    execute: async ({ prompt, size }) => {
      const p = await pickImageProvider();
      if (!p) {
        return {
          error:
            "No image-generation key configured (google/openai/xai). Add one in Settings → Models.",
        };
      }
      try {
        let gen: ImageGen;
        if (p.provider === "google") {
          gen = (await import("@/modules/ai/lib/media/google-image")).generateGoogleImage;
        } else if (p.provider === "openai") {
          gen = (await import("@/modules/ai/lib/media/openai-image")).generateOpenAIImage;
        } else {
          gen = (await import("@/modules/ai/lib/media/xai-image")).generateXAIImage;
        }
        const result = await gen(p.key, { prompt, size });
        await deliver("image", result, prompt);
        return {
          ok: true,
          provider: p.provider,
          width: result.width,
          height: result.height,
          delivered: true,
        };
      } catch (e) {
        return { error: e instanceof Error ? e.message : String(e) };
      }
    },
  });

  const generateVideo = tool({
    description:
      "Generate a short video from a text prompt (5-30s) with Google Veo 3.1, using the configured Google key. The video is delivered to the chat when ready; generation takes 1-5 minutes. If the user wants a different engine (Kling, Seedance…), tell them to install that vendor's MCP server in the desktop app's Settings → MCP.",
    inputSchema: z.object({
      prompt: z.string().describe("Scene description: subject, motion, camera work, mood."),
      duration: z.number().min(5).max(30).optional().describe("Duration in seconds (5-30). Default 5."),
      aspect_ratio: z.string().optional().describe("Aspect ratio like '16:9' or '9:16'. Default 16:9."),
    }),
    execute: async ({ prompt, duration, aspect_ratio }) => {
      const p = await pickVideoProvider();
      if (!p) {
        return {
          error: "No Google API key configured — video generation needs one (Settings → Models). Other engines are available via their MCP servers.",
        };
      }
      try {
        const gen = (await import("@/modules/ai/lib/media/google-video")).generateGoogleVideo;
        const result = await gen(p.key, {
          prompt,
          duration,
          aspectRatio: aspect_ratio,
        });
        await deliver("video", result, prompt);
        return { ok: true, provider: p.provider, delivered: true };
      } catch (e) {
        return { error: e instanceof Error ? e.message : String(e) };
      }
    },
  });

  return { generate_image: generateImage, generate_video: generateVideo };
}

// Re-export for callers that need to check key availability without building
// the tools (e.g. a status line).
export async function mediaProviderStatus(): Promise<{ image: boolean; video: boolean }> {
  const [img, vid] = await Promise.all([pickImageProvider(), pickVideoProvider()]);
  return { image: img != null, video: vid != null };
}
